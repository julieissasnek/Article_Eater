def generate_theory_id(name: str) -> str:
    """Generate a theory ID from name."""
    # Convert to snake_case
    clean = name.lower()
    clean = clean.replace(' ', '_')
    clean = clean.replace('-', '_')
    clean = ''.join(c for c in clean if c.isalnum() or c == '_')
    return f"theory:{clean}"


def generate_prediction_id(theory_id: str, index: int) -> str:
    """Generate a prediction ID."""
    theory_short = theory_id.replace('theory:', '')
    return f"pred:{theory_short}:{index:03d}"


def generate_claim_id(theory_id: str, index: int) -> str:
    """Generate a claim ID."""
    theory_short = theory_id.replace('theory:', '')
    return f"claim:{theory_short}:{index:02d}"


def compute_derivation_confidence(chain: List[DerivationStep], base_confidence: float = 0.9) -> float:
    """
    Compute confidence in a derived prediction based on chain length and step types.
    
    Each step reduces confidence multiplicatively:
    - Deductive: 0.95
    - Inductive: 0.85
    - Analogical: 0.75
    """
    step_factors = {
        'deductive': 0.95,
        'inductive': 0.85,
        'analogical': 0.75,
        'default': 0.80,
    }
    
    confidence = base_confidence
    for step in chain:
        factor = step_factors.get(step.inference_type, step_factors['default'])
        confidence *= factor
    
    return round(confidence, 3)
