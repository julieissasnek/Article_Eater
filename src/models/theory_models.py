@dataclass
class Originator:
    """Author/paper that originated or developed a theory."""
    name: str
    year: Optional[int] = None
    doi: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class TheoryClaim:
    """A core claim or proposition of a theory."""
    claim_id: str
    theory_id: str
    statement: str
    formalization: Optional[str] = None
    necessity: Necessity = Necessity.CORE
    testability: Testability = Testability.DIRECTLY_TESTABLE
    created_at: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d['necessity'] = self.necessity.value
        d['testability'] = self.testability.value
        return d


@dataclass
class TheoryAssumption:
    """An assumption that a theory relies upon."""
    assumption_id: str
    theory_id: str
    statement: str
    dependent_claims: List[str] = field(default_factory=list)  # claim_ids
    violation_consequence: Optional[str] = None
    created_at: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class TheoryBoundary:
    """A boundary condition where theory may not apply."""
    boundary_id: str
    theory_id: str
    condition_description: str
    evidence_for_boundary: List[str] = field(default_factory=list)  # citations
    mechanism_of_failure: Optional[str] = None
    confidence_penalty: float = 0.0
    created_at: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class DerivationStep:
    """A single step in a derivation chain."""
    claim_id: str
    inference_type: str  # e.g., "deductive", "inductive", "analogical"
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class QuantitativePrediction:
    """Quantitative aspects of a prediction."""
    point_estimate: Optional[float] = None
    ci_lower: Optional[float] = None
    ci_upper: Optional[float] = None
    functional_form: Optional[str] = None  # For complex relationships
    
    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class Prediction:
    """A prediction derived from or explicit in a theory."""
    prediction_id: str
    source_theory_id: str
    statement: str
    prediction_type: PredictionType
    
    # Antecedent conditions
    antecedent_env_conditions: List[Dict[str, Any]] = field(default_factory=list)
    antecedent_population: List[Dict[str, Any]] = field(default_factory=list)
    antecedent_temporal: Optional[Dict[str, Any]] = None
    antecedent_state: List[Dict[str, Any]] = field(default_factory=list)
    
    # Consequent
    consequent_outcome: str = ""
    consequent_direction: Direction = Direction.POSITIVE
    consequent_magnitude: Magnitude = Magnitude.UNSPECIFIED
    consequent_mechanism: Optional[str] = None
    relation_type: RelationType = RelationType.PROBABILISTIC
    
    # Derivation
    derivation_chain: List[DerivationStep] = field(default_factory=list)
    auxiliary_assumptions: List[str] = field(default_factory=list)
    
    # Quantitative
    quantitative: Optional[QuantitativePrediction] = None
    
    # Scope
    generality: Generality = Generality.DOMAIN_SPECIFIC
    applicable_populations: List[str] = field(default_factory=list)
    applicable_contexts: List[str] = field(default_factory=list)
    known_exceptions: List[str] = field(default_factory=list)
    
    # Testing status
    testing_status: TestingStatus = TestingStatus.UNTESTED
    overall_support: SupportLevel = SupportLevel.UNTESTED
    test_summary: Optional[str] = None
    
    # Confidence
    prior_confidence: float = 0.5
    current_confidence: float = 0.5
    theory_contribution: float = 0.0
    derivation_contribution: float = 0.0
    empirical_contribution: float = 0.0
    uncertainty_type: UncertaintyType = UncertaintyType.EPISTEMIC
    
    # Network mapping
    maps_to_edge_id: Optional[str] = None
    maps_to_nodes: List[str] = field(default_factory=list)
    contributes_prior: bool = True
    prior_weight: float = 1.0
    
    # Metadata
    extraction_source: Optional[str] = None
    created_at: Optional[str] = None
    updated_at: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        d = {
            'prediction_id': self.prediction_id,
            'source_theory_id': self.source_theory_id,
            'statement': self.statement,
            'prediction_type': self.prediction_type.value,
            'antecedent_env_conditions': self.antecedent_env_conditions,
            'antecedent_population': self.antecedent_population,
            'antecedent_temporal': self.antecedent_temporal,
            'antecedent_state': self.antecedent_state,
            'consequent_outcome': self.consequent_outcome,
            'consequent_direction': self.consequent_direction.value,
            'consequent_magnitude': self.consequent_magnitude.value,
            'consequent_mechanism': self.consequent_mechanism,
            'relation_type': self.relation_type.value,
            'derivation_chain': [s.to_dict() for s in self.derivation_chain],
            'auxiliary_assumptions': self.auxiliary_assumptions,
            'quantitative': self.quantitative.to_dict() if self.quantitative else None,
            'generality': self.generality.value,
            'applicable_populations': self.applicable_populations,
            'applicable_contexts': self.applicable_contexts,
            'known_exceptions': self.known_exceptions,
            'testing_status': self.testing_status.value,
            'overall_support': self.overall_support.value,
            'test_summary': self.test_summary,
            'prior_confidence': self.prior_confidence,
            'current_confidence': self.current_confidence,
            'theory_contribution': self.theory_contribution,
            'derivation_contribution': self.derivation_contribution,
            'empirical_contribution': self.empirical_contribution,
            'uncertainty_type': self.uncertainty_type.value,
            'maps_to_edge_id': self.maps_to_edge_id,
            'maps_to_nodes': self.maps_to_nodes,
            'contributes_prior': self.contributes_prior,
            'prior_weight': self.prior_weight,
            'extraction_source': self.extraction_source,
            'created_at': self.created_at,
            'updated_at': self.updated_at,
        }
        return d


