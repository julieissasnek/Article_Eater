from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import List, Dict, Any, Optional
from datetime import datetime
import json


# ============================================================
# ENUMS
# ============================================================

class TheoryLevel(Enum):
    """Hierarchical level of theoretical abstraction."""
    META_PRINCIPLE = "meta_principle"  # Most abstract (e.g., "moderate stimulation is optimal")
    THEORY = "theory"  # Unified explanatory framework (e.g., Predictive Processing)
    PRINCIPLE = "principle"  # Domain-specific regularity (e.g., "nature exposure reduces stress")
    MECHANISM = "mechanism"  # Pathway specification (e.g., "daylight → circadian → mood")


class Necessity(Enum):
    """Whether a claim is essential to the theory."""
    CORE = "core"  # Theory could not survive without this claim
    AUXILIARY = "auxiliary"  # Elaborates but not essential


class Testability(Enum):
    """How directly testable a claim is."""
    DIRECTLY_TESTABLE = "directly_testable"
    INDIRECTLY_TESTABLE = "indirectly_testable"
    FRAMEWORK = "framework"  # Provides structure but not directly testable


class PredictionType(Enum):
    """Source of a prediction."""
    EXPLICIT = "explicit"  # Stated by theory originators
    DERIVED = "derived"  # Logically implied by core claims
    NEWLY_DERIVED = "newly_derived"  # Generated by system inference


class Direction(Enum):
    """Predicted direction of effect."""
    POSITIVE = "positive"
    NEGATIVE = "negative"
    NULL = "null"
    INVERTED_U = "inverted_u"
    COMPLEX = "complex"


class Magnitude(Enum):
    """Predicted magnitude of effect."""
    STRONG = "strong"
    MODERATE = "moderate"
    WEAK = "weak"
    UNSPECIFIED = "unspecified"


class RelationType(Enum):
    """Type of relationship predicted."""
    DETERMINISTIC = "deterministic"
    PROBABILISTIC = "probabilistic"
    TENDENCY = "tendency"


class Generality(Enum):
    """Scope of prediction applicability."""
    UNIVERSAL = "universal"
    DOMAIN_SPECIFIC = "domain_specific"
    POPULATION_SPECIFIC = "population_specific"
    CONTEXT_SPECIFIC = "context_specific"


class TestingStatus(Enum):
    """How well-tested a prediction is."""
    UNTESTED = "untested"
    PARTIALLY_TESTED = "partially_tested"
    WELL_TESTED = "well_tested"
    DISCONFIRMED = "disconfirmed"


class SupportLevel(Enum):
    """Overall empirical support for a prediction."""
    STRONGLY_SUPPORTED = "strongly_supported"
    SUPPORTED = "supported"
    MIXED = "mixed"
    UNSUPPORTED = "unsupported"
    DISCONFIRMED = "disconfirmed"
    UNTESTED = "untested"


class TestType(Enum):
    """How a study relates to testing a prediction."""
    DIRECT = "direct"  # Designed to test this prediction
    INDIRECT = "indirect"  # Bears on prediction but not designed for it
    INCIDENTAL = "incidental"  # Implications not recognized by authors


class TestResult(Enum):
    """Outcome of an empirical test."""
    SUPPORTS = "supports"
    PARTIAL = "partial"
    NULL = "null"
    CONTRADICTS = "contradicts"


class TestStrength(Enum):
    """Methodological strength of a test."""
    STRONG = "strong"
    MODERATE = "moderate"
    WEAK = "weak"


class ReplicationStatus(Enum):
    """Overall replication record of a theory."""
    STRONG = "strong"
    MODERATE = "moderate"
    MIXED = "mixed"
    WEAK = "weak"
    CONTESTED = "contested"


class ContributionType(Enum):
    """How a paper contributes to a theory."""
    ORIGINATION = "origination"
    REFINEMENT = "refinement"
    EXTENSION = "extension"
    CRITIQUE = "critique"
    INTEGRATION = "integration"
    REVIEW = "review"


class UncertaintyType(Enum):
    """Source of uncertainty in a prediction."""
    ALEATORY = "aleatory"  # Inherent randomness
    EPISTEMIC = "epistemic"  # Lack of knowledge
    BOTH = "both"


