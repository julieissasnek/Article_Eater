@dataclass
class Theory:
    """A complete theoretical framework."""
    theory_id: str
    name: str
    aliases: List[str] = field(default_factory=list)
    
    # Origins
    originators: List[Originator] = field(default_factory=list)
    year_introduced: Optional[int] = None
    
    # Structure
    domain: List[str] = field(default_factory=list)  # Domain IDs
    scope_description: Optional[str] = None
    level: TheoryLevel = TheoryLevel.THEORY
    
    # Components (populated separately)
    core_claims: List[TheoryClaim] = field(default_factory=list)
    assumptions: List[TheoryAssumption] = field(default_factory=list)
    boundary_conditions: List[TheoryBoundary] = field(default_factory=list)
    
    # Predictions (populated separately)
    explicit_predictions: List[Prediction] = field(default_factory=list)
    derived_predictions: List[Prediction] = field(default_factory=list)
    
    # Confidence
    overall_confidence: float = 0.5
    confidence_rationale: Optional[str] = None
    quantitative_precision: str = "low"  # high, medium, low, none
    
    # Relations
    parent_theories: List[str] = field(default_factory=list)  # theory_ids
    child_theories: List[str] = field(default_factory=list)
    compatible_theories: List[str] = field(default_factory=list)
    competing_theories: List[str] = field(default_factory=list)
    
    # Evidence
    replication_status: ReplicationStatus = ReplicationStatus.MODERATE
    
    # Metadata
    extraction_source: Optional[str] = None
    extracted_by: Optional[str] = None
    version: int = 1
    created_at: Optional[str] = None
    updated_at: Optional[str] = None
    
    @property
    def all_predictions(self) -> List[Prediction]:
        """Return all predictions (explicit and derived)."""
        return self.explicit_predictions + self.derived_predictions
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'theory_id': self.theory_id,
            'name': self.name,
            'aliases': self.aliases,
            'originators': [o.to_dict() for o in self.originators],
            'year_introduced': self.year_introduced,
            'domain': self.domain,
            'scope_description': self.scope_description,
            'level': self.level.value,
            'core_claims': [c.to_dict() for c in self.core_claims],
            'assumptions': [a.to_dict() for a in self.assumptions],
            'boundary_conditions': [b.to_dict() for b in self.boundary_conditions],
            'explicit_predictions': [p.to_dict() for p in self.explicit_predictions],
            'derived_predictions': [p.to_dict() for p in self.derived_predictions],
            'overall_confidence': self.overall_confidence,
            'confidence_rationale': self.confidence_rationale,
            'quantitative_precision': self.quantitative_precision,
            'parent_theories': self.parent_theories,
            'child_theories': self.child_theories,
            'compatible_theories': self.compatible_theories,
            'competing_theories': self.competing_theories,
            'replication_status': self.replication_status.value,
            'extraction_source': self.extraction_source,
            'extracted_by': self.extracted_by,
            'version': self.version,
            'created_at': self.created_at,
            'updated_at': self.updated_at,
        }
    
    def to_json(self) -> str:
        """Serialize to JSON."""
        return json.dumps(self.to_dict(), indent=2)
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'Theory':
        """Deserialize from dictionary."""
        # Convert nested structures
        originators = [Originator(**o) for o in data.get('originators', [])]
        
        core_claims = []
        for c in data.get('core_claims', []):
            c['necessity'] = Necessity(c['necessity']) if isinstance(c['necessity'], str) else c['necessity']
            c['testability'] = Testability(c['testability']) if isinstance(c['testability'], str) else c['testability']
            core_claims.append(TheoryClaim(**c))
        
        assumptions = [TheoryAssumption(**a) for a in data.get('assumptions', [])]
        boundary_conditions = [TheoryBoundary(**b) for b in data.get('boundary_conditions', [])]
        
        # Handle level enum
        level = data.get('level', 'theory')
        if isinstance(level, str):
            level = TheoryLevel(level)
        
        # Handle replication_status enum
        replication_status = data.get('replication_status', 'moderate')
        if isinstance(replication_status, str):
            replication_status = ReplicationStatus(replication_status)
        
        return cls(
            theory_id=data['theory_id'],
            name=data['name'],
            aliases=data.get('aliases', []),
            originators=originators,
            year_introduced=data.get('year_introduced'),
            domain=data.get('domain', []),
            scope_description=data.get('scope_description'),
            level=level,
            core_claims=core_claims,
            assumptions=assumptions,
            boundary_conditions=boundary_conditions,
            overall_confidence=data.get('overall_confidence', 0.5),
            confidence_rationale=data.get('confidence_rationale'),
            quantitative_precision=data.get('quantitative_precision', 'low'),
            parent_theories=data.get('parent_theories', []),
            child_theories=data.get('child_theories', []),
            compatible_theories=data.get('compatible_theories', []),
            competing_theories=data.get('competing_theories', []),
            replication_status=replication_status,
            extraction_source=data.get('extraction_source'),
            extracted_by=data.get('extracted_by'),
            version=data.get('version', 1),
            created_at=data.get('created_at'),
            updated_at=data.get('updated_at'),
        )


